// utils/questCompletionPolicy.ts
// Политика пропусков: сколько точек надо реально пройти, чтобы прохождение
// квеста было засчитано (#1443).
//
// Решение (17.08.2026): «квест засчитан» требует ответов минимум на ДВЕ ТРЕТИ
// обязательных точек маршрута, с округлением вверх. Ниже порога прохождение
// считается частичным: игрок видит финал и сохраняет прогресс, но значка,
// звания «первопроходца» и `completed: true` на бэкенде не получает.
//
// Почему порог, а не «хотя бы один ответ»: пропуск точки существует для двух
// честных случаев — далёкая точка (#1432) и протухшее задание, на котором игрок
// застрял (#1430). Оба выбивают из маршрута единицы точек, а не весь маршрут.
// Порог в две трети такие случаи пропускает (пропуск 1–3 точек из 9 остаётся
// полноценным прохождением) и при этом закрывает вырожденный: ответить на одну
// точку, пропустить остальные и получить значок с «первопроходцем».
//
// Почему доля, а не абсолютный минимум: в квестах от 5 до 12 обязательных
// точек, и «минимум 5 точек» означал бы для короткого квеста весь маршрут, а
// для длинного — меньше половины.
//
// Почему округление вверх: у квеста из 9 точек порог 6 (пропустить можно 3), из
// 5 — 4 (пропустить можно 1). Округление вниз давало бы на коротком маршруте
// лишний пропуск.

// Порог держим дробью из целых, а не готовым `0.666…`: умножение на двоичную
// дробь читается как правило только до тех пор, пока совпадает с ним численно, а
// целочисленный числитель совпадает с ним по построению.
const COMPLETION_MIN_NUMERATOR = 2
const COMPLETION_MIN_DENOMINATOR = 3

/**
 * Сколько обязательных точек надо пройти, чтобы квест засчитался.
 * Для квеста без обязательных точек порог нулевой — засчитывать нечего.
 */
export const questCompletionThreshold = (requiredCount: number): number => {
  if (!Number.isFinite(requiredCount) || requiredCount <= 0) return 0
  return Math.ceil((requiredCount * COMPLETION_MIN_NUMERATOR) / COMPLETION_MIN_DENOMINATOR)
}

/** Сколько точек не хватает до засчитанного прохождения (0 — хватает). */
export const questStepsMissingForCompletion = (requiredCount: number, answeredCount: number): number =>
  Math.max(0, questCompletionThreshold(requiredCount) - answeredCount)
