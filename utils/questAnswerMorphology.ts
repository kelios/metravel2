// utils/questAnswerMorphology.ts
//
// Второй проход проверки текстового ответа: словоформа эталона (#1631).
//
// Зачем он вообще нужен. `normalize()` в `questAdapters.ts` приводит только
// косметику — регистр, пробелы, пунктуацию и «ё». Сравнение после неё строгое,
// поэтому принимаемым остаётся ровно то, что редактор перечислил руками. Форма
// слова, которую провоцирует само задание, в словарь при этом попадает не
// всегда: шаг 136 `brest-fortress / holmskie` просил «Напиши одно слово», а в
// словаре лежали только `пули` и `снаряды`. Живой игрок 25.08.2026 получил
// девять отказов подряд на `снаряд` и `пуля` — это те же слова из того же
// словаря, только в единственном числе, — и прошёл шаг с десятой попытки.
// Оценка по всей базе: 116 из 744 шагов `exact_any` содержат вариант во
// множественном числе без формы единственного.
//
// Почему не морфология в `normalize()`. Нормализация симметрична и применяется
// к обеим сторонам ДО сравнения: сведи она падежи, и словарь начал бы принимать
// то, чего в нём нет, без единого следа в данных шага. Здесь наоборот — проход
// ВТОРОЙ и срабатывает только после провала строгого сравнения, поэтому он
// физически не способен отменить уже работающий ответ. Он умеет лишь принять
// дополнительную форму, и цена ошибки односторонняя.
//
// Почему не стеммер. Snowball сводит `пуля`, `пулемёт` и `пулять` к одной
// основе — для проверки ответа это слишком грубо. Здесь работает более узкое
// правило: слова обязаны совпадать до самого хвоста, а оба хвоста — быть
// настоящими окончаниями русского или белорусского словоизменения.

/**
 * Окончания русского и белорусского словоизменения (существительные и
 * прилагательные, все три рода, оба числа). Пустая строка — нулевое окончание
 * (`снаряд` против `снаряды`).
 */
const ENDINGS = new Set([
    '',
    // существительные, RU
    'а', 'я', 'ы', 'и', 'у', 'ю', 'е', 'о', 'ь', 'й',
    'ой', 'ей', 'ою', 'ею', 'ом', 'ем', 'ам', 'ям', 'ах', 'ях', 'ов', 'ев',
    'ами', 'ями', 'ией', 'иях',
    // прилагательные и причастия, RU
    'ый', 'ий', 'ая', 'яя', 'ое', 'ее', 'ые', 'ым', 'им', 'ых', 'их',
    'ую', 'юю', 'ому', 'ему', 'ого', 'его', 'ыми', 'ими',
    // BE
    'і', 'ў', 'аў', 'еў', 'ай', 'яй', 'амі', 'ямі',
    'ае', 'яе', 'ыя', 'ія', 'ага', 'яга', 'аму', 'яму', 'ім', 'іх',
])

/**
 * Минимальная длина каждого из сравниваемых слов. Отсекает короткие пары
 * разных слов, которые различаются ровно окончанием: `рот` против `рота`,
 * `пол` против `пола`. Для пары `пуля` / `пули` (обе по четыре буквы) правило
 * выполняется, и именно ради неё порог не поднят выше.
 */
const MIN_WORD_LENGTH = 4

/**
 * Минимальная общая часть. Три буквы — это `пул` в паре `пуля` / `пули`;
 * меньше уже не отличает словоформу от другого слова.
 */
const MIN_COMMON_PREFIX = 3

/** Длиннее трёх букв русское или белорусское окончание не бывает. */
const MAX_ENDING_LENGTH = 3

const commonPrefixLength = (a: string, b: string): number => {
    const limit = Math.min(a.length, b.length)
    let i = 0
    while (i < limit && a[i] === b[i]) i += 1
    return i
}

/**
 * Числительные словами. Проект уже держит правило «другое число — это другой
 * ответ, а не описка» для цифр (`docs/QUEST_ANSWER_INSIGHTS.md`), и словесная
 * запись обязана подчиняться тому же правилу: `пять` и `пятый` — количество
 * против порядка, а не две формы одного слова, хотя различаются они ровно
 * окончанием. Замер по базе показал эту пару на `minsk-cipher / 5-kolas`.
 * Правило одностороннее: если хотя бы одно слово числительное, работает только
 * строгое сравнение.
 */
const NUMERALS = new Set([
    'один', 'одна', 'одно', 'два', 'две', 'три', 'четыре', 'пять', 'шесть', 'семь',
    'восемь', 'девять', 'десять', 'одиннадцать', 'двенадцать', 'тринадцать',
    'четырнадцать', 'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать',
    'девятнадцать', 'двадцать', 'тридцать', 'сорок', 'пятьдесят', 'сто',
    'первый', 'первая', 'первое', 'второй', 'вторая', 'второе', 'третий', 'третья',
    'третье', 'четвертый', 'четвертая', 'пятый', 'пятая', 'шестой', 'шестая',
    'седьмой', 'седьмая', 'восьмой', 'восьмая', 'девятый', 'девятая', 'десятый',
    'десятая', 'дюжина', 'адзін', 'адна', 'адно', 'два', 'дзве', 'тры',
    'чатыры', 'пяць', 'шэсць', 'сем', 'восем', 'дзевяць', 'дзесяць',
])

/**
 * Однословный текст без цифр и не числительное — только такие пары проходят
 * морфологический разбор.
 */
const isMorphComparable = (value: string): boolean =>
    value.length >= MIN_WORD_LENGTH
    && !value.includes(' ')
    && !/\d/.test(value)
    && !NUMERALS.has(value)

/**
 * Беглая гласная: `щенок` → `щенка`, `петушок` → `петушка`, `отец` → `отца`.
 * В косвенных падежах гласная суффикса выпадает, и основа перестаёт совпадать с
 * именительным падежом — то самое место, где сравнение хвостов бессильно.
 * Возвращает усечённую основу или `null`, если чередование неприменимо.
 *
 * Замер по базе 2026-08-29: 48 шагов из 744 содержат вариант на `-ок`/`-ек`/
 * `-ец`, у которого в словаре нет ни одной формы с усечённой основой, — то есть
 * игрок, написавший `щенка` там, где в словаре `щенок`, получал отказ.
 */
const fleetingVowelStem = (word: string): string | null => {
    const match = /^(.{2,})(?:о|е)(к|ц)$/.exec(word)
    return match ? match[1] + match[2] : null
}

const matchesByEndings = (input: string, variant: string): boolean => {
    const common = commonPrefixLength(input, variant)
    if (common < MIN_COMMON_PREFIX) return false

    const inputEnding = input.slice(common)
    const variantEnding = variant.slice(common)
    if (inputEnding.length > MAX_ENDING_LENGTH || variantEnding.length > MAX_ENDING_LENGTH) return false

    return ENDINGS.has(inputEnding) && ENDINGS.has(variantEnding)
}

const isSameSingleWordForm = (input: string, variant: string): boolean => {
    if (input === variant) return true
    if (!isMorphComparable(input) || !isMorphComparable(variant)) return false
    if (matchesByEndings(input, variant)) return true

    // Третья попытка — уже с учётом выпавшей гласной. Сравниваем ввод не с самим
    // вариантом, а с его усечённой основой: `щенка` против `щенк`.
    const variantStem = fleetingVowelStem(variant)
    if (variantStem && matchesByEndings(input, variantStem)) return true

    // И зеркально: в словаре косвенная форма, а игрок пишет именительный.
    const inputStem = fleetingVowelStem(input)
    return !!inputStem && matchesByEndings(inputStem, variant)
}

/**
 * Ввод и эталон — формы одного ответа.
 *
 * Обе строки уже прошли `normalize()`. Числа и числительные исключены
 * сознательно: другое число — это другой ответ, а не описка (то же правило
 * держит классификатор `quest-answer-insights`, где `33` не имеет права стать
 * синонимом `6`).
 *
 * Составной ответ (`от пуль` против `от пули`) сравнивается ПОСЛОВНО и только
 * при равном числе слов: каждое слово обязано быть формой своего, порядок
 * обязан совпасть. Это строже однословного случая, а не мягче — совпасть должны
 * все слова сразу. На проде 18 шагов, где ВСЕ варианты словаря многословные:
 * без пословного разбора морфология обходила бы их стороной.
 */
export const isSameWordForm = (input: string, variant: string): boolean => {
    if (input === variant) return true

    const inputWords = input.split(' ')
    const variantWords = variant.split(' ')
    if (inputWords.length !== variantWords.length) return false
    if (inputWords.length === 1) return isSameSingleWordForm(input, variant)

    return inputWords.every((word, i) => {
        const target = variantWords[i]
        // Служебные слова (`от`, `из`, `в`) короче четырёх букв и морфологии не
        // подлежат — от них требуется буквальное совпадение.
        return word === target || isSameSingleWordForm(word, target)
    })
}

/** Совпадает ли ввод хотя бы с одним вариантом словаря по форме слова. */
export const matchesAnyWordForm = (input: string, variants: readonly string[]): boolean =>
    variants.some((variant) => isSameWordForm(input, variant))
