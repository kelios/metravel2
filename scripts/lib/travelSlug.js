/**
 * scripts/lib/travelSlug.js
 * Слаг, который бэкенд выдаст статье по её заголовку — предсказание ДО записи.
 *
 * #1690: `seo-alias-backfill` переименовывает живую статью дважды и рассчитывает,
 * что второе переименование вернёт её на прежний адрес. Это верно ровно тогда,
 * когда `slugify(заголовок)` совпадает с текущим слагом. У части старых статей
 * это не так (слаг писала другая версия транслитератора либо заголовок правился
 * мимо слага) — и прогон уводит проиндексированную статью на чужой адрес.
 * Проверить инвариант можно только заранее: после записи возвращать уже нечем.
 *
 * Бэкенд считает слаг как `slugify(name)` из python-slugify 8.0.4
 * (`travels/services/slug_service.py`). Порядок шагов там такой, и модель ниже
 * повторяет именно его — порядок сокращать нельзя, на нём и ловятся расхождения:
 *
 *   1. ASCII-апостроф `'` → дефис (ДО транслитерации)
 *   2. NFKD + unidecode — транслитерация, РЕГИСТР ЕЩЁ ИСХОДНЫЙ
 *   3. раскрытие HTML-сущностей (`&amp;`, `&#8470;`, `&#x2014;`)
 *   4. lower() — только теперь
 *   5. остатки апострофов удаляются без следа
 *   6. запятая МЕЖДУ ЦИФРАМИ удаляется: `1,5` → `15`
 *   7. всё вне `[-a-z0-9]` → дефис, дубли дефисов схлопываются, края обрезаются
 *
 * Шаг 2 раньше шага 4 — не деталь: `unidecode('Є')` даёт `E`, а `unidecode('є')`
 * даёт `ie`, поэтому таблица обязана спрашиваться ИСХОДНЫМ символом, а не
 * приведённым к нижнему регистру. Свип по U+0400–U+052F и Latin-1/Extended-A
 * показал ровно одну такую асимметрию среди букв, которые здесь вообще есть.
 *
 * Главное правило модуля: неизвестный символ — это `null`, а не догадка.
 * Ошибиться в сторону «предсказать не берусь» стоит пропущенного алиаса;
 * ошибиться в другую сторону стоит канонического адреса живой статьи.
 */

/** Кириллица RU + BE/UK-специфика: text-unidecode, снято прогоном по алфавиту. */
const CYRILLIC = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'i', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh',
  щ: 'shch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'iu', я: 'ia',
  і: 'i', ў: 'u', ї: 'i', є: 'ie', ґ: 'g',
}

/**
 * Буквы, у которых развёртка заглавной НЕ равна развёртке строчной. Ищутся по
 * исходному символу до `toLowerCase()`, иначе заголовок «Свято Єднання» получил
 * бы предсказание `sviato-iednannia` вместо настоящего `sviato-ednannia`.
 */
const UPPERCASE_EXCEPTIONS = { Є: 'e' }

/** Латиница, которую NFKD не раскладывает: у неё своя развёртка в unidecode. */
const LATIN_LIGATURES = {
  ß: 'ss', ł: 'l', ø: 'o', æ: 'ae', œ: 'oe', đ: 'd', ð: 'd', þ: 'th',
}

/**
 * Знаки, исчезающие без следа: типографские апострофы, мягкий перенос,
 * невидимые склейки и четыре «тире», которые unidecode удаляет вместо дефиса —
 * U+05BE (маккаф), U+1806 (монгольский перенос), U+10D6E (гарайский),
 * U+10EAD (езидский). Не путать с U+200B и U+2060 — те дают разделитель.
 */
const DROPPED = new Set([
  '\u2018', '\u2019', '\u00ad', '\u200c', '\u200d', '\ufeff',
  '\u05be', '\u1806', '\u{10d6e}', '\u{10ead}',
])

/**
 * Разделители за пределами ASCII — СПИСОК, а не категория. Соблазн написать
 * `\p{Pd}` здесь ошибочен в опасную сторону: множество тире растёт вместе с ICU
 * ноды, а таблица text-unidecode на бэкенде заморожена, поэтому каждое новое
 * тире Юникода молча стало бы разделителем в модели и пустотой на бэкенде —
 * fail-open в модуле, у которого главное правило «неизвестное — это отказ».
 * Список снят перебором ВСЕХ `\p{Zs} ∪ \p{Pd}` (44 символа) через саму
 * библиотеку: 40 дают разделитель, 4 удаляются (см. `DROPPED`), прочих нет.
 * ASCII-пробел и дефис сюда не входят — их разбирает ветка ASCII выше.
 * Всё, чего в списке нет, доходит до `return null` и уходит в отказ.
 */
const SEPARATOR = new RegExp(
  '[\\u00a0\\u058a\\u1400\\u1680\\u2000-\\u200a\\u2010-\\u2015\\u202f\\u205f' +
    '\\u2e17\\u2e1a\\u2e3a\\u2e3b\\u2e40\\u2e5d\\u3000\\u301c\\u3030\\u30a0' +
    '\\ufe31\\ufe32\\ufe58\\ufe63\\uff0d' +
    '\\u200b\\u2060\\u00ab\\u00bb\\u201c\\u201d\\u201e\\u2039\\u203a\\u2026\\u2022\\u00b7]',
  'u'
)

/**
 * Диакритика, которую unidecode снимает без следа: ровно эти диапазоны, снятые
 * прогоном по блокам. Остальные комбинирующие знаки он превращает в разделитель
 * (U+034F–U+035F) или прямо в текст — U+0489 даёт «1 000 000», — поэтому
 * огульное «снять все \p{M}» было бы догадкой, а не моделью.
 */
const DROPPED_MARKS = /[\u0300-\u034e\u0360-\u0362\u0483-\u0486\u20d0-\u20e3]/u
const ANY_MARK = /\p{M}/u

/** `&amp;`, `&#8470;`, `&#x2014;` — бэкенд их раскрывает, и снова через unidecode. */
const HTML_ENTITY = /&(#\d+|#x[\da-fA-F]+|[a-zA-Z][a-zA-Z0-9]*);/

/**
 * Слаг, который бэкенд поставит статье с таким заголовком, либо `null`, если в
 * заголовке есть символ вне таблиц — «не знаю» вызывающая сторона обязана
 * читать как отказ от прогона.
 */
function expectedTravelSlug(name) {
  const raw = String(name == null ? '' : name)
  // Сущность раскрывается в юникод, который потом снова идёт через unidecode.
  // Моделировать это второй таблицей значит ставить догадку поверх догадки.
  if (HTML_ENTITY.test(raw)) return null

  const source = raw
    .replace(/'/g, '-') // шаг 1: ASCII-апостроф становится разделителем
    .normalize('NFKD')
  // Транслитерация (шаг 2) идёт по ИСХОДНОМУ регистру, а ASCII тут не трогаем:
  // запятая между цифрами обязана дожить до шага 6, не став раньше дефисом.
  let out = ''
  for (const char of source) {
    if (DROPPED.has(char)) continue
    if (ANY_MARK.test(char)) {
      if (DROPPED_MARKS.test(char)) continue
      return null
    }
    const exception = UPPERCASE_EXCEPTIONS[char]
    if (exception !== undefined) {
      out += exception
      continue
    }
    if (char.codePointAt(0) < 128) {
      out += char
      continue
    }
    const lower = char.toLowerCase()
    const cyrillic = CYRILLIC[lower]
    if (cyrillic !== undefined) {
      out += cyrillic
      continue
    }
    const ligature = LATIN_LIGATURES[lower]
    if (ligature !== undefined) {
      out += ligature
      continue
    }
    if (SEPARATOR.test(char)) {
      out += ' '
      continue
    }
    return null
  }

  const slug = out
    .toLowerCase() // шаг 4
    .replace(/'/g, '') // шаг 5: апострофы из unidecode уходят без следа
    .replace(/(\d),(?=\d)/g, '$1') // шаг 6: `1,5` → `15`
    .replace(/[^a-z0-9-]+/g, '-') // шаг 7
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
  // Пустой результат бэкенд заменяет литералом `travel` — предсказывать такой
  // заголовок значит гадать, поэтому он тоже уходит в отказ.
  return slug || null
}

/**
 * Расхождение «заголовок не даёт текущий слаг» словами оператора, либо `null`,
 * если расхождения нет. Коллизионный суффикс называется отдельно: это самый
 * частый повод, и владельцу от него нужно другое решение, чем от правки текста.
 */
function describeSlugMismatch(name, currentSlug) {
  const expected = expectedTravelSlug(name)
  if (expected === null) {
    return {
      expected: null,
      reason:
        `слаг заголовка «${name}» предсказать нечем: в нём есть символ вне таблицы транслитерации. ` +
        'Пока предсказания нет, переименование могло бы увести статью на чужой адрес',
    }
  }
  if (expected === currentSlug) return null
  const collisionSuffix = new RegExp(`^${expected.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}-\\d+$`)
  if (collisionSuffix.test(currentSlug)) {
    return {
      expected,
      reason:
        `слаг «${currentSlug}» оканчивается коллизионным суффиксом: заголовок даёт «${expected}» без него, ` +
        'поэтому возврат сменил бы канонический адрес живой статьи. Нужно решение владельца — ' +
        'либо алиас пишет бэкенд-миграция, либо статья осознанно переезжает на чистый слаг',
    }
  }
  return {
    expected,
    reason:
      `заголовок «${name}» даёт слаг «${expected}», а статья сидит на «${currentSlug}»: возврат сменил бы ` +
      'канонический адрес живой статьи. Нужно решение владельца — либо алиас пишет бэкенд-миграция, ' +
      'либо статья осознанно переезжает на слаг своего заголовка',
  }
}

module.exports = { expectedTravelSlug, describeSlugMismatch }
