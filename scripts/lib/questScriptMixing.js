/**
 * scripts/lib/questScriptMixing.js
 * Поиск слов, внутри которых перемешаны кириллица и латиница.
 *
 * Правило одно на весь квест-контент: слово целиком набирается одним алфавитом.
 * Нарушение выглядит невинно — «гадзiннiк» с латинской `i` и «гадзіннік» с
 * белорусской `і` неразличимы глазом, — но бьёт в двух разных местах:
 *   - в словаре ответа `exact_any` вариант становится недостижим, игрок не может
 *     набрать его ни на одной раскладке (#1450 нашёл класс, #1455 починил шесть);
 *   - в видимом тексте шага (`story`/`task`/`hint`/`title`/`location`) игрок
 *     читает опечатку: «brusчатка», «площадь Луža», «память о морe» (#1464).
 *
 * Помощник вынесен в `lib/`, потому что оба скана обязаны считать смешение
 * ОДИНАКОВО: разойдись копии регулярками хоть на один диапазон — и один скан
 * начал бы отчитываться «чисто» о том, что другой считает дефектом.
 */

const CYRILLIC = /[Ѐ-ӿԀ-ԯ]/
const LATIN = /[A-Za-zÀ-ɏ]/

/**
 * Слова с перемешанными алфавитами. Считаем по СЫРОМУ тексту, а не по
 * нормализованному: `normalize()` срезает дефис, и «SPA-центр» превратился бы в
 * «spaцентр» — ложный вердикт «набрать нельзя» для формы, которую игрок
 * прекрасно вводит. Разделитель — любой не-буквенный символ: «кафе Bar» и
 * «SPA-центр» нормальные двуязычные записи, а «гадзiннiк» с латинской `i`
 * внутри одного слова не наберёт никто.
 */
function mixedScriptWords(rawValue) {
  return String(rawValue == null ? '' : rawValue)
    .split(/[^\p{L}]+/u)
    .filter((word) => word && CYRILLIC.test(word) && LATIN.test(word))
}

/** Буквы алфавита-меньшинства в слове — чтобы находку можно было проверить глазами. */
function confusableChars(word) {
  const cyrillic = word.match(/[Ѐ-ӿԀ-ԯ]/g) || []
  const latin = word.match(/[A-Za-zÀ-ɏ]/g) || []
  const minority = cyrillic.length >= latin.length ? latin : cyrillic
  return [...new Set(minority)].join('')
}

module.exports = { mixedScriptWords, confusableChars, CYRILLIC, LATIN }
