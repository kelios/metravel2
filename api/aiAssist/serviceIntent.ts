/** Вопрос о самом сайте, а не о поездке — на RU/BE/UK/PL/EN. */
export const asksAboutService = (question: string | null | undefined): boolean => {
  const text = String(question ?? '')
  if (!text.trim()) return false
  if (SERVICE_RE.test(text)) return true
  if (PRICE_RE.test(text) && SERVICE_OBJECT_RE.test(text)) return true
  return QUEST_HOWTO_RE.test(text) && QUEST_OBJECT_RE.test(text)
}
