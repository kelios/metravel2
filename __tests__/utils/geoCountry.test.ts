import { getCountryCodeByCoords } from '@/utils/geoCountry';

type Fixture = readonly [name: string, lat: number, lng: number, expected: string | undefined];

const expectAll = (fixtures: readonly Fixture[]) => {
  const actual = fixtures.map(([name, lat, lng]) => `${name}=${getCountryCodeByCoords(lat, lng)}`);
  const wanted = fixtures.map(([name, , , expected]) => `${name}=${expected}`);
  expect(actual).toEqual(wanted);
};

describe('getCountryCodeByCoords', () => {
  it('resolves Sarajevo to BA, not the overlapping IT/HR boxes', () => {
    // Регресс: у Сараево на бэке country_code=null, поэтому группировка идёт
    // через этот фолбэк. Раньше широкий bbox Италии (а затем Хорватии)
    // перехватывал точку, и город уходил в IT/HR вместо Боснии.
    expect(getCountryCodeByCoords(43.8563, 18.4131)).toBe('BA');
  });

  it('resolves core Italian cities to IT', () => {
    expect(getCountryCodeByCoords(41.9028, 12.4964)).toBe('IT'); // Рим
  });

  it('returns undefined for coordinates outside known boxes', () => {
    expect(getCountryCodeByCoords(0, 0)).toBeUndefined();
  });

  // Регресс #1370: прямоугольник России (41.19–81.86 N, 19.64–180 E) стоял четвёртым
  // и забирал весь Кавказ, Прибалтику и Среднюю Азию — travel «Тбилиси и Батуми»
  // получал партнёрские ссылки на российские отели.
  it('does not let the Russian box swallow the Caucasus, the Baltics and Central Asia', () => {
    expectAll([
      ['Тбилиси', 41.7151, 44.8271, 'GE'],
      ['Батуми', 41.6168, 41.6367, 'GE'],
      ['Кутаиси', 42.2679, 42.6946, 'GE'],
      ['Ереван', 40.1792, 44.4991, 'AM'],
      ['Гюмри', 40.7894, 43.8475, 'AM'],
      ['Баку', 40.4093, 49.8671, 'AZ'],
      ['Нахичевань', 39.209, 45.4122, 'AZ'],
      ['Ленкорань', 38.7529, 48.8511, 'AZ'],
      ['Рига', 56.9496, 24.1052, 'LV'],
      ['Даугавпилс', 55.8747, 26.5362, 'LV'],
      ['Таллин', 59.437, 24.7536, 'EE'],
      ['Тарту', 58.378, 26.729, 'EE'],
      ['Алматы', 43.222, 76.8512, 'KZ'],
      ['Астана', 51.1694, 71.4491, 'KZ'],
      ['Уральск', 51.2333, 51.3667, 'KZ'],
      ['Петропавловск', 54.8667, 69.15, 'KZ'],
    ]);
  });

  // Реальные координаты точек travel 213 «Тбилиси и Батуми: маршрут по Грузии»
  // с прода — именно этот маршрут получал партнёрские ссылки на российские отели.
  it('resolves the real route points of travel 213 (production fixture)', () => {
    expectAll([
      ['Тбилисский ботанический сад', 41.6873906, 44.8022161, 'GE'],
      ['Парк Мтацминда', 41.6948646, 44.7868652, 'GE'],
      ['Мост Мира', 41.6929692, 44.8084388, 'GE'],
      ['Танцующие фонтаны, Батуми', 41.641431, 41.6133592, 'GE'],
      ['Киев (точка того же маршрута)', 50.4500336, 30.5241361, 'UA'],
    ]);
  });

  // Вильнюс лежит внутри прямоугольника Беларуси, Кишинёв — внутри украинского.
  it('resolves cities that sit inside the Belarusian and Ukrainian boxes', () => {
    expectAll([
      ['Вильнюс', 54.6872, 25.2797, 'LT'],
      ['Каунас', 54.8985, 23.9036, 'LT'],
      ['Друскининкай', 54.02, 23.97, 'LT'],
      ['Кишинёв', 47.0105, 28.8638, 'MD'],
      ['Бельцы', 47.7615, 27.9291, 'MD'],
      ['Кагул', 45.907, 28.194, 'MD'],
    ]);
  });

  // Контрольная группа: перестановка России вниз списка ломала ровно это —
  // сибирские города уходили в KZ, а Приэльбрусье и Северный Кавказ — в GE.
  it('keeps Russian cities in RU, including the ones near the Georgian and Kazakh borders', () => {
    expectAll([
      ['Москва', 55.7558, 37.6173, 'RU'],
      ['Санкт-Петербург', 59.9311, 30.3609, 'RU'],
      ['Владивосток', 43.1155, 131.8855, 'RU'],
      ['Новосибирск', 55.0084, 82.9357, 'RU'],
      ['Омск', 54.9885, 73.3242, 'RU'],
      ['Челябинск', 55.1644, 61.4368, 'RU'],
      ['Уфа', 54.7388, 55.9721, 'RU'],
      ['Барнаул', 53.3548, 83.7698, 'RU'],
      ['Оренбург', 51.7727, 55.0988, 'RU'],
      ['Эльбрус', 43.3499, 42.4453, 'RU'],
      ['Владикавказ', 43.0241, 44.6814, 'RU'],
      ['Грозный', 43.3169, 45.6981, 'RU'],
      ['Домбай', 43.287, 41.626, 'RU'],
      ['Сочи', 43.5855, 39.7231, 'RU'],
      ['Махачкала', 42.9764, 47.5024, 'RU'],
      ['Калининград', 54.7104, 20.4522, 'RU'],
      ['Псков', 57.8194, 28.332, 'RU'],
      ['Мурманск', 68.9585, 33.0827, 'RU'],
      ['Якутск', 62.0355, 129.6755, 'RU'],
      ['Петропавловск-Камчатский', 53.037, 158.6559, 'RU'],
    ]);
  });

  it('keeps Belarusian and Ukrainian cities out of the neighbouring boxes', () => {
    expectAll([
      ['Минск', 53.9006, 27.559, 'BY'],
      ['Гродно', 53.6884, 23.8258, 'BY'],
      ['Ошмяны', 54.4234, 25.9375, 'BY'],
      ['Браслав', 55.6395, 27.0417, 'BY'],
      ['Брест', 52.0976, 23.7341, 'BY'],
      ['Киев', 50.4501, 30.5234, 'UA'],
      ['Одесса', 46.4825, 30.7233, 'UA'],
      ['Черновцы', 48.2921, 25.9358, 'UA'],
      ['Измаил', 45.3512, 28.8365, 'UA'],
      ['Львов', 49.8397, 24.0297, 'UA'],
      ['Ужгород', 48.6208, 22.2879, 'UA'],
    ]);
  });

  // Соседи, у которых контура нет: они резолвятся прямоугольниками и не должны
  // пострадать от того, что RU/BY/UA ушли на отдельную ступень.
  it('still resolves neighbours that rely on plain boxes', () => {
    expectAll([
      ['Варшава', 52.2297, 21.0122, 'PL'],
      ['Сувалки', 54.1117, 22.9309, 'PL'],
      ['Щецин', 53.4285, 14.5528, 'PL'],
      ['Будапешт', 47.4979, 19.0402, 'HU'],
      ['Бухарест', 44.4268, 26.1025, 'RO'],
      ['Яссы', 47.1585, 27.6014, 'RO'],
      ['Стамбул', 41.0082, 28.9784, 'TR'],
      ['Карс', 40.6013, 43.0975, 'TR'],
      ['Ташкент', 41.2995, 69.2401, 'UZ'],
      ['Урумчи', 43.8256, 87.6168, 'CN'],
      // Прямоугольник Чехии лежит внутри польского, поэтому саксонские и
      // баварские города должны разбираться раньше — Чехия стоит ниже Германии.
      ['Дрезден', 51.0504, 13.7373, 'DE'],
      ['Хемниц', 50.8278, 12.9214, 'DE'],
      ['Пассау', 48.5667, 13.4319, 'DE'],
      ['Регенсбург', 49.0134, 12.1016, 'DE'],
    ]);
  });

  // Крым в Natural Earth 10m отнесён к России. Резолвер отдавал его Украине и
  // после смены датасета обязан отдавать так же: тихо переопределить это вместе
  // с технической правкой геометрии нельзя.
  it('keeps Crimea on the pre-existing resolution', () => {
    expectAll([
      ['Симферополь', 44.9521, 34.1024, 'UA'],
      ['Ялта', 44.4952, 34.1663, 'UA'],
      ['Севастополь', 44.6166, 33.5254, 'UA'],
      ['Керчь', 45.3531, 36.4744, 'UA'],
    ]);
  });

  // Прибрежный допуск применяется ко всему периметру контура, поэтому он узкий:
  // иначе приграничные города соседа уезжают за границу.
  it('does not hand border towns to the neighbour through the coastal tolerance', () => {
    expectAll([
      ['Медыка (PL, 2 км до границы)', 49.8103, 22.9297, 'PL'],
      ['Пыталово (RU, у границы с LV)', 57.064, 27.925, 'RU'],
      ['Печоры (RU, у границы с EE)', 57.814, 27.615, 'RU'],
      ['Советск (RU, у границы с LT)', 55.08, 21.88, 'RU'],
      // Куршская коса: контур Литвы её не покрывает, точку добирает прямоугольник.
      ['Нида', 55.3033, 21.0064, 'LT'],
      ['Клайпеда', 55.7033, 21.1443, 'LT'],
      ['Актау (берег Каспия)', 43.635, 51.168, 'KZ'],
    ]);
  });

  // Прямоугольник России накрывал Финляндию и север Норвегии, которых в таблице
  // нет. Ложная «Россия» хуже неизвестности: потребители умеют работать с undefined
  // (нейтральная партнёрская ссылка вместо ссылки на отели не той страны).
  it('returns undefined instead of RU for countries the table does not cover', () => {
    expectAll([
      ['Хельсинки', 60.1699, 24.9384, undefined],
      ['Рованиеми', 66.5039, 25.7294, undefined],
      ['Киркенес', 69.727, 30.045, undefined],
    ]);
  });
});
