// Зачем отдельная фикстура, а не корпус реальных отказов. Корпус
// `questRejectedAnswerCorpus` сторожит состав списка `ENDINGS` — отключение
// списка он ловит пятью конкретными вводами. Пороги длины он не сторожит, и
// это не догадка, а замер по живой базе 2026-08-30:
//
//   - среди 97 отклонённых попыток `quest_answer_attempt` нет ни одной пары
//     «ввод + вариант его шага» с общим префиксом ровно 2 буквы и валидными
//     окончаниями с обеих сторон, то есть снижение `MIN_COMMON_PREFIX` 3 → 2
//     корпусом недоказуемо;
//   - среди 2451 однословного варианта из 703 живых словарей такие пары есть,
//     но их всего три и все родственные: `змей`/`змий`, `змей`/`змія`,
//     `змий`/`змія`. Принять их друг за друга — не ошибка правила, поэтому
//     доказательной отрицательной парой они быть не могут.
//
// Вывод замера: данных для корпусного контроля порогов в проекте пока нет, и
// ждать их — значит оставить границу без стража. Поэтому пороги охраняются
// прямым контрактом: настоящие слова русского языка, которые НЕ являются
// формами друг друга, но склеились бы ровно при ослаблении одного порога.
//
// Почему здесь только `MIN_COMMON_PREFIX`. Замером 2026-08-30 проверены все три
// порога, и в одиночку пробивается ровно один. `MIN_WORD_LENGTH` 4 → 3 не
// склеивает ничего: чтобы правило сработало, обе стороны обязаны иметь валидное
// окончание, а у трёхбуквенного слова после общей части в три буквы хвост пустой
// (`рот` / `рота` → хвосты «» и «а»), и пустая строка окончанием не считается.
// `MAX_ENDING_LENGTH` 3 → 4 не склеивает ничего по той же причине: в `ENDINGS`
// нет ни одного четырёхбуквенного окончания. Оба порога держит не собственное
// значение, а состав `ENDINGS`, который уже сторожит корпус реальных отказов.
// Дублировать этот контроль пустыми записями значило бы создать ложное
// спокойствие, поэтому фикстура их не содержит.
//
// Каждая запись обязана быть красной при ослаблении и зелёной на текущем
// правиле; тест `questMorphologyBoundaries.test.ts` проверяет обе стороны.

