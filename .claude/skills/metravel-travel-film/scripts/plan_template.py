#!/usr/bin/env python3
"""План серии __TAG__ для render_plan.py. Здесь только сцены; общая механика — film_serial.py скилла metravel-travel-film.

Запуск: `film.py plan __TAG__` (или python3 -I plan___TAG__.py <plan.json> из папки планов).
Пути, название серии, интро сериала и «ранее» — в film.json рядом. Номера сцен в заметках = номера сцен сценария:
«N. …» — сцена, «рассказ:» в заметке — кусок рамки-рассказа, «0.» — интро сериала, «T.» — тизер и концовка.
Правила монтажа — references/screenplay.md и review-rubric.md: план ≥ 4 с, перебивка — только того, о чём говорят.
"""
import os, sys
sys.path.insert(0, os.environ.get("FILM_SCRIPTS") or "__SK__")       # scripts скилла metravel-travel-film
import film_serial as S
from film_serial import clip, story, file_seg, rv, ph, photo_seg, card, put, PREP, MAPS, CARDS

TAG = "__TAG__"
EP = S.series(TAG)["n"]                       # номер серии и её дни — film.json → series
D = (S.series(TAG)["days"] or [1])[0]         # день по умолчанию для clip/story/ph
S.start(TAG, teaser="T.", intro=("0.",), auto_level=True)   # auto_level: уровни музыки под речью и на видах ставит рендер

# ---------------------------------------------------------------- 0. интро сериала + «ранее в сериале»
S.serial_intro(EP)                            # кадры и голос — film.json → intro, recap; не описаны — пропускается

# ---------------------------------------------------------------- сцены
# >>> сцены
# sg = clip(D, "C0001", 2.0, 14.0, "1. приехали")                          живой план: день, часть имени файла, от, до, заметка
# put(sg, card("место", "__TAG__ место вокзал", "Руан · вокзал"), 0.5, 4.0)    плашка места на отрезке: через 0,5 с на 4 с
# clip(D, "C0002", 0.5, 6.5, "1. вид на город", mute=True)                  вид без звука места — под музыку
# clip(D, "C0003", note="2. рассказ у моря", over=[rv(D, "C0004"), ph(D, 1805, 5)], each=5.0)   перебивки поверх говорящего
# <<< сцены

# Кусок рассказа по словам расшифровки (от первой фразы до конца второй), перебивки — после 4 с лица:
# story(D, "C0005", "сегодня мы идём", "до самого города", note="3. рассказ: план дня", over=[rv(D, "C0006")])
# Карта дня и фото на главной дорожке:
# file_seg(MAPS + "/День 1.mp4", 0, 10.5, "4. карта дня");  photo_seg(D, 1806, 4.0, "4. фото: завтрак")
# Справка (заголовок + строки) и цена:  put(sg, card("справка", "__TAG__ справка маяк", "Маяк", "построен в 1895 году"), 2.0, 6.0)

S.end_card()                                  # концовка metravel.by — последним отрезком («T. …»)

# ---------------------------------------------------------------- общие проходы (порядок важен)
S.fit_broll_to_files()
CUT = os.path.join(S.HERE, "перебивки_" + TAG + ".json")     # таблица «мысль → кадр» (shot_catalog.py): есть — перебивки только из неё
if os.path.exists(CUT):
    S.cutaways(CUT, day=D); S.fit_broll_to_files()
S.join_runs()                                 # соседние куски одного рассказа — встык
S.whole_phrases()                             # края живой речи — по целой фразе
S.vertical_main()                             # вертикальные куски → задания vertical_jobs_<серия>.json
S.no_flashes()
S.fit_broll_to_files()
S.loudness()                                  # речь к −14 LUFS, фон места к −26
S.blur_substitute()                           # размытые копии (лица, номера) — когда серия утверждена
S.transitions_and_edges()

# ---------------------------------------------------------------- голос и музыка
S.serial_intro_sound(EP)
# S.voice("В1 связка", PREP + "/1 сценарий/голос/В1.wav", "1. вид на город", a_off=0.3)   голос за кадром: с 0,3 с отрезка
S.part_beds()                                 # музыка по частям дня: части_<серия>.json + разбор треков (film.py music)
S.duck_beds()
S.dedupe_broll()
S.fit_broll_to_files()
# Рамка-рассказ («рассказ:» в заметках): тёплые копии перебивок, окошко рассказчика, «вжух» на входе и выходе —
# S.memory_look({"3. рассказ": "25 мая · утро"}, card("блок", TAG + " вспоминаем", "Вспоминаем", "26 мая · рассказываем про 25-е"))
# S.whooshes()
S.save(sys.argv[1])
