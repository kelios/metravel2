import { useAuthStore } from '@/stores/authStore';

/**
 * Владелец личного кэша React Query (#1831).
 *
 * Личный ключ обязан нести владельца сам — тогда чужие данные не читаются даже
 * если сброс кэша на смене сессии (`api/identityQueryCache.ts`, #1829) однажды
 * не отработает. Хук — единственный источник этого значения, чтобы двадцать с
 * лишним ключей не выводили владельца каждый по-своему.
 *
 * Гость — `null`, а не `undefined` и не `'guest'`: пустая ячейка гостя тоже
 * обязана отличаться от ячейки любого вошедшего.
 *
 * `isAuthenticated` в условии — не защита от окна в сторе: `invalidateAuthState`
 * гасит `isAuthenticated` и `userId` одним `set` (`stores/authStore.ts:229`), и
 * состояния «вышел, но владелец остался» там не бывает. Условие держит другое:
 * дословное совпадение с выражением личности, по которому сбрасывается кэш на
 * смене владельца (`stores/authStore.ts:629`). Разойдись эти два выражения —
 * владелец в ключе и граница сброса указывали бы на разные сессии.
 */
export const useQueryOwner = (): string | null =>
  useAuthStore((state) => (state.isAuthenticated ? state.userId : null));
