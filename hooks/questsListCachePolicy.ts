// hooks/questsListCachePolicy.ts
// Политика кеша единственного ключа queryKeys.quests().
//
// Вынесено отдельным листовым модулем намеренно: константы нужны и хлебным
// крошкам, которые живут в шапке на каждом маршруте, а импорт их из
// `useQuestsApi` затягивал бы в стартовый граф весь слой данных квестов
// (`api/quests` → `questAdapters` → `geoCountry` → таблица контуров стран).
// Здесь не должно появиться ни одного импорта.

// Полный список квестов кешируется под одним ключом queryKeys.quests(), чтобы
// экран квестов, промо-блок главной, крошка города и три мета-хука детали
// (rating/completion/pioneer) дедуплицировались в один запрос /quests/.
// Держим список «свежим» ~30 мин и в кеше ~60 мин.
export const QUESTS_LIST_STALE_TIME = 30 * 60 * 1000;
export const QUESTS_LIST_GC_TIME = 60 * 60 * 1000;
