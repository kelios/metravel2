// components/trips/planning/tripPlanRouteMap.types.ts
// Общий контракт web- и native-варианта карты конструктора маршрута: оба файла
// платформенные, а типы у них обязаны совпадать (как у TripRouteFilePicker).

/**
 * #1495: запрос «покажи эту точку». `token` растёт на каждый тап по точке в
 * списке — по нему карта понимает, что цель нужно показать снова, даже если
 * координаты те же самые.
 */
export type MapFocusPoint = {
  lat: number;
  lng: number;
  token: number;
};

/** Зум, на который карта встаёт при центрировании на точке маршрута. */
export const FOCUS_POINT_ZOOM = 14;

/**
 * #1781: запрос «перенеси эту точку сюда». Карта только сообщает намерение —
 * владелец черновика (`RouteBuilder`) решает, как применить его к маршруту.
 */
export type RoutePointMove = {
  index: number;
  lat: number;
  lng: number;
};

/**
 * Шаг округления координат точки маршрута. Один и тот же для ручного ввода и
 * перетаскивания маркера: сохранение маршрута на бэкенде пересоздаёт строки
 * точек и выдаёт им НОВЫЕ id, поэтому идентичность точки для карты держится на
 * координатах, а не на id (#1781).
 */
export const ROUTE_POINT_COORDINATE_PRECISION = 6;

/**
 * #1820: счётчик оптовых замен маршрута — применения шаблона и импорта трека.
 * Растёт на каждую такую замену и служит картам единственным признаком «маршрут
 * заменили целиком, покажи получившийся»: снимает защёлку кадра, поставленную
 * перетаскиванием маркера, и разрешает подгонку.
 *
 * Сигнал, а не вывод из данных: повторное применение ТОГО ЖЕ шаблона возвращает
 * неперетащенные точки с прежними координатами, поэтому по самим точкам оптовую
 * замену от частичной правки не отличить (#1820).
 */
export type RouteReplacementToken = number;
