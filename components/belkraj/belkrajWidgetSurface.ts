// Подложка под сторонний виджет партнёрских предложений (belkraj.by/partner/widget).
//
// Страница партнёра приходит с `body { background: rgba(255, 255, 255, 0) }` и
// жёстко светлой палитрой текста: заголовок `#3f93c3`, названия карточек
// `#2c3945`/`#354859`, подписи `#868789`. Своей темы у неё нет — проверено
// 02.09.2026 запросами к виджету: `scheme=dark`, `dark=1` и `color_scheme=dark`
// отдают байт-в-байт тот же светлый HTML, а `theme=` у партнёра означает
// раскладку (`cards`), а не палитру.
//
// Значит фон под прозрачной страницей обязаны дать мы, и он всегда светлый — иначе
// в тёмной теме тёмные названия карточек ложатся на тёмный `colors.surface`
// (1.22:1 при `#2c3945` на `#2a2a2a`, репорт TestFlight #1697). Здесь берётся
// именно СВЕТЛАЯ палитра напрямую, а не `useThemedColors()`/`var(--color-surface)`:
// оба следуют теме, и подложка снова уехала бы в тёмное.
//
// Обе платформы (`BelkrajWidget.tsx` и `BelkrajWidget.native.tsx`) читают эту
// константу, чтобы фон виджета не разошёлся между web, Android и iOS. Значение
// берётся из `DESIGN_COLORS`, а не из палитры напрямую: `designSystem.ts` — её
// единственный разрешённый импортёр (правило там же, у `getThemedColors`).
import { DESIGN_COLORS } from '@/constants/designSystem'

export const BELKRAJ_WIDGET_SURFACE: string = DESIGN_COLORS.staticLightSurface
