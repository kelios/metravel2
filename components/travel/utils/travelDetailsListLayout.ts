import { METRICS } from '@/constants/layout'

/**
 * Оценка ширины КОЛОНКИ списков travel-details («Рядом» и «Популярное»), чтобы
 * `TravelListItem` считал ступень srcSet обложки по реальной колонке, а не по
 * фолбэку от вьюпорта (#1544, механика #1487/#1285 «sizes = ширина отрисовки»).
 *
 * Без явного `cardWidth` `TravelListItem` берёт `min(viewport, 720)` и объявляет
 * `sizes="720px"` на колонке ~280 px — браузер тянет ступень w=720 (~72–147 КБ)
 * там, где хватает w=320/480 (~24–40 КБ). Замер прода 2026-08-24, desktop 1280.
 *
 * Значение ОБЯЗАНО быть оценкой СВЕРХУ (никогда ниже реальной колонки), иначе
 * обложка получит ступень мельче слота и станет мылом. Поэтому:
 *  - внутри-колоночные зазоры (`gap`) НЕ вычитаются — так остаётся запас сверху;
 *  - для 3 колонок база ширины срезана на desktop-брейкпоинте (см. ниже).
 *
 * Замеры реальной колонки на проде (DPR 1, `energylandia-…`):
 *   vw 1024 → 307 · 1280 → 285 · 1440 → 317 · 1600 → 352 · 1920 → 348.
 * Немонотонность объясняется тем, что левое меню деталей появляется только с
 * `width >= desktop(1280)` (`shouldShowTravelDetailsDesktopSidebar`): ниже
 * брейкпоинта сетка занимает ~весь вьюпорт и колонка растёт до пика ~392 (≈1279),
 * с брейкпоинта flex-меню сужает её обратно до 285–352 (контент упирается в
 * shell maxWidth 1600).
 */

// Горизонтальная «обвязка» страницы (паддинги контентной колонки + скроллбар
// desktop) вокруг сетки списков. Замер прода 2026-08-24 при vw=1024 (меню ещё
// нет): ширина сетки 953 px → 1024 − 953 = 71 px.
const PAGE_HORIZONTAL_CHROME = 71

// Верхний потолок ступени для одноколоночного (во всю ширину) слота: не
// анонсируем отрисовку крупнее w=720, даже если колонка формально шире.
const SINGLE_COLUMN_WIDTH_CAP = 720

export function getTravelDetailsListColumnWidth(
  viewportWidth: number,
  numColumns: number,
): number {
  const cols = Math.max(1, Math.floor(numColumns) || 1)
  const vw =
    Number.isFinite(viewportWidth) && viewportWidth > 0 ? viewportWidth : 1024

  if (cols >= 3) {
    // База ширины срезана на desktop-брейкпоинте: с него появляется flex-меню и
    // сужает колонку, поэтому пик «без меню» (~392 при 1279) доминирует над
    // всеми колонками с меню (285–352). (1280 − 71) / 3 = 403 — безопасный
    // потолок для любого vw ≥ 1024.
    const base = Math.min(vw, METRICS.breakpoints.desktop)
    return Math.round((base - PAGE_HORIZONTAL_CHROME) / cols)
  }

  if (cols === 2) {
    // 768–1023: меню ещё нет, контент ≈ вьюпорт.
    return Math.round((vw - PAGE_HORIZONTAL_CHROME) / cols)
  }

  // Одна колонка занимает почти всю ширину контента.
  return Math.min(Math.round(vw), SINGLE_COLUMN_WIDTH_CAP)
}
