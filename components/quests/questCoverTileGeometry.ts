/**
 * Геометрия медиа-плитки карточки квеста (`QuestForCityCard`), #1542.
 *
 * Плитка — ФИКСИРОВАННЫЙ квадрат. Это осознанное решение, а не следствие
 * вёрстки: карточка квеста живёт в горизонтальном рейле (главная,
 * `QuestNextStepSection`, `QuestForCitySection`), и слот из пропорций каждой
 * обложки дал бы соседям в одном ряду разную высоту — ровно тот вид, который
 * владелец отклонил 2026-08-24 на карточках маршрутов (#1487).
 *
 * При обязательном `contain` (docs/RULES.md → «Images and placeholders») это
 * значит, что плоское поле убирается только КОНТЕНТОМ — квадратным вариантом
 * обложки (прецедент #134/#152), а не клиентским `cover` и не переразмером
 * слота. Замер прода 2026-08-25 по всем 156 квестам `/api/quests/?compact=1`:
 * квадратных обложек 0, весь набор ландшафтный (1.333…1.778), поле 12.5…21.9%.
 *
 * Константы вынесены из компонента, чтобы регресс-тест
 * `__tests__/components/quests/questCoverTileLetterbox.test.ts` считал долю
 * поля по источнику истины, а не по литералу у себя в файле.
 */

/** Сторона квадратной медиа-плитки карточки квеста, CSS px. */
export const QUEST_TILE_MEDIA_SIZE = 132

/**
 * Пропорция медиа-слота плитки. Единица — квадрат, и она НЕ функция обложки:
 * если слот начнёт считаться от `aspect_ratio` кадра, рейл потеряет
 * выравнивание. Охраняется тестом #1542.
 */
export const QUEST_TILE_SLOT_RATIO = 1

/**
 * Высота плитки. Считается через пропорцию, а не вторым литералом: так
 * `QUEST_TILE_SLOT_RATIO` остаётся несущей константой, и уход слота от
 * квадрата виден и в разметке, и в тесте, а не только в комментарии.
 */
export const QUEST_TILE_MEDIA_HEIGHT = QUEST_TILE_MEDIA_SIZE / QUEST_TILE_SLOT_RATIO

/**
 * Сторона плитки на телефоне (<480pt), CSS px. #1673.
 *
 * Плитка остаётся квадратом и константой — инвариант рейла из шапки файла не
 * трогается: все карточки одного экрана берут одну и ту же сторону, потому что
 * развилка идёт по ширине ЭКРАНА, а не по кадру конкретной обложки.
 *
 * Величина взята из замера, а не на глаз. Карточка — горизонтальный ряд, и при
 * стороне 132 на 390pt тексту оставалось 202px: замер прод-выдачи
 * `/api/quests/?compact=1` (165 названий, 18px/700, lineHeight 23) дал 17
 * названий, которым нужно ЧЕТЫРЕ строки, — они и резались. Сторона 96 отдаёт
 * заголовку 238px, и на всей выдаче не остаётся ни одного названия длиннее трёх
 * строк.
 */
export const QUEST_TILE_MEDIA_SIZE_COMPACT = 96

/** Высота компактной плитки — через ту же пропорцию, что и основная. */
export const QUEST_TILE_MEDIA_HEIGHT_COMPACT =
  QUEST_TILE_MEDIA_SIZE_COMPACT / QUEST_TILE_SLOT_RATIO
