// #2119: где существует окно настроек книги.
import { Platform } from 'react-native'

/**
 * Окно настроек книги (`BookSettingsModal`: тема, раскладка галереи, обложка,
 * чеклисты) написано DOM-разметкой — `<div>`, `<select>`, `<input>` — и на native
 * не рендерится. В приложениях книга печатается с настройками по умолчанию:
 * каталог — кнопкой «Сохранить PDF» (она и на сайте печатает без окна), одно
 * путешествие — сразу по нажатию. Окно настроек для приложений — #2229; когда
 * оно появится, этот ответ станет `true` везде.
 */
export function isBookSettingsWindowAvailable(): boolean {
  return Platform.OS === 'web'
}
